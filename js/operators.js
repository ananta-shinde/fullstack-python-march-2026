console.log("true"*false)
console.log("true"*20)
console.log("true"*"20")
console.log(100*20)

// / operator : division, returns quotient   // can only be possible with numbers and boolean values
console.log("result of / operator")
console.log(true*true)
console.log("true"*false)
console.log("true"*20)
